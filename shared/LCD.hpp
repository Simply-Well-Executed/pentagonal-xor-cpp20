#ifndef LCD_HPP
#define LCD_HPP

using U = unsigned long long;

static_assert(~U{0} == 18446744073709551615ULL);

struct L {
    U a, c;
};

[[nodiscard]]
constexpr L LCD(U a, U c) noexcept {
    if (!c) return {a, 0};

    U x = a, y = c;

    while (y) {
        const U r = x % y;
        x = y;
        y = r;
    }

    return {a/x, c/x};
}

#endif
